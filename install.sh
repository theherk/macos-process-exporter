#!/bin/bash
set -euo pipefail

# macOS Process Exporter - Install Script
#
# This script:
# 1. Installs prometheus and grafana via Homebrew (if not present)
# 2. Copies config.example.yml to config.yml (if not already customized)
# 3. Symlinks prometheus config into Homebrew prefix
# 4. Configures Grafana provisioning to point at bundled dashboards
# 5. Installs a root LaunchDaemon for the exporter
# 6. Starts all services
#
# Prerequisites:
# - macOS (Apple Silicon or Intel)
# - Homebrew installed
# - uv installed (via mise, brew, or pipx)

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PLIST_NAME="com.local.macos-process-exporter"
PLIST_DEST="/Library/LaunchDaemons/${PLIST_NAME}.plist"

# --- Check prerequisites ---
if ! command -v brew &>/dev/null; then
    echo "ERROR: Homebrew is required. Install from https://brew.sh"
    exit 1
fi

if ! command -v uv &>/dev/null; then
    echo "ERROR: uv is required. Install via: brew install uv"
    exit 1
fi

BREW_PREFIX="$(brew --prefix)"
GRAFANA_INI="${BREW_PREFIX}/etc/grafana/grafana.ini"

echo "==> macOS Process Exporter Installer"
echo "    Install directory: ${SCRIPT_DIR}"
echo "    Homebrew prefix:   ${BREW_PREFIX}"
echo ""

# --- Install brew dependencies ---
echo "==> Installing prometheus and grafana..."
brew install prometheus grafana 2>/dev/null || true

# --- Config file ---
if [ ! -f "${SCRIPT_DIR}/config.yml" ]; then
    echo "==> Creating config.yml from example..."
    cp "${SCRIPT_DIR}/config.example.yml" "${SCRIPT_DIR}/config.yml"
    echo "    Edit config.yml to customize which processes to track."
else
    echo "==> config.yml already exists, skipping."
fi

# --- Prometheus config (symlinks) ---
echo "==> Symlinking Prometheus configuration..."

# Generate prometheus.args from template with correct brew prefix
sed "s|__BREW_PREFIX__|${BREW_PREFIX}|g" \
    "${SCRIPT_DIR}/prometheus.args.template" \
    > "${SCRIPT_DIR}/prometheus.args"

ln -sf "${SCRIPT_DIR}/prometheus.yml" "${BREW_PREFIX}/etc/prometheus.yml"
ln -sf "${SCRIPT_DIR}/prometheus.args" "${BREW_PREFIX}/etc/prometheus.args"

# --- Grafana provisioning ---
echo "==> Configuring Grafana provisioning..."

# Generate default.yml from template with correct install path
sed "s|__INSTALL_DIR__|${SCRIPT_DIR}|g" \
    "${SCRIPT_DIR}/grafana/provisioning/dashboards/default.yml.template" \
    > "${SCRIPT_DIR}/grafana/provisioning/dashboards/default.yml"

# Set Grafana's provisioning path in grafana.ini
if [ -f "${GRAFANA_INI}" ]; then
    if grep -q "^provisioning = " "${GRAFANA_INI}"; then
        sed -i '' "s|^provisioning = .*|provisioning = ${SCRIPT_DIR}/grafana/provisioning|" "${GRAFANA_INI}"
    elif grep -q "^;provisioning = " "${GRAFANA_INI}"; then
        sed -i '' "s|^;provisioning = .*|provisioning = ${SCRIPT_DIR}/grafana/provisioning|" "${GRAFANA_INI}"
    else
        echo "provisioning = ${SCRIPT_DIR}/grafana/provisioning" >> "${GRAFANA_INI}"
    fi
    echo "    Grafana provisioning path set."
else
    echo "WARNING: ${GRAFANA_INI} not found. You may need to configure Grafana manually."
fi

# --- Detect Grafana port conflict ---
GRAFANA_PORT=3000
if lsof -i :3000 -sTCP:LISTEN &>/dev/null; then
    echo "    Port 3000 is in use, configuring Grafana on port 3001..."
    if [ -f "${GRAFANA_INI}" ]; then
        if grep -q "^http_port = " "${GRAFANA_INI}"; then
            sed -i '' "s|^http_port = .*|http_port = 3001|" "${GRAFANA_INI}"
        elif grep -q "^;http_port = " "${GRAFANA_INI}"; then
            sed -i '' "s|^;http_port = .*|http_port = 3001|" "${GRAFANA_INI}"
        fi
    fi
    GRAFANA_PORT=3001
fi

# --- Generate run.sh ---
echo "==> Generating run.sh wrapper..."
UV_PATH="$(command -v uv)"
cat > "${SCRIPT_DIR}/run.sh" << EOF
#!/bin/bash
# Auto-generated by install.sh - runs the exporter as root via uv.
export HOME="${HOME}"
# Keep root's uv cache separate so root never creates root-owned files in the user's ~/.cache/uv.
export UV_CACHE_DIR="/var/root/.cache/uv"
export PATH="$(dirname "${UV_PATH}"):${BREW_PREFIX}/bin:/usr/local/bin:/usr/bin:/bin"
exec ${UV_PATH} run --script ${SCRIPT_DIR}/exporter.py
EOF
chmod +x "${SCRIPT_DIR}/run.sh"

# --- Generate and install LaunchDaemon ---
echo "==> Installing LaunchDaemon (requires sudo)..."
cat > "/tmp/${PLIST_NAME}.plist" << EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>${PLIST_NAME}</string>

    <key>ProgramArguments</key>
    <array>
        <string>${SCRIPT_DIR}/run.sh</string>
    </array>

    <key>UserName</key>
    <string>root</string>

    <key>RunAtLoad</key>
    <true/>

    <key>KeepAlive</key>
    <true/>

    <key>StandardOutPath</key>
    <string>${SCRIPT_DIR}/exporter.log</string>

    <key>StandardErrorPath</key>
    <string>${SCRIPT_DIR}/exporter.err</string>

    <key>WorkingDirectory</key>
    <string>${SCRIPT_DIR}</string>

    <key>ProcessType</key>
    <string>Background</string>

    <key>LowPriorityIO</key>
    <true/>

    <key>Nice</key>
    <integer>10</integer>
</dict>
</plist>
EOF

sudo cp "/tmp/${PLIST_NAME}.plist" "${PLIST_DEST}"
sudo chown root:wheel "${PLIST_DEST}"
sudo chmod 644 "${PLIST_DEST}"
rm "/tmp/${PLIST_NAME}.plist"

# --- Start services ---
echo "==> Starting services..."

# Stop existing exporter if running
sudo launchctl unload "${PLIST_DEST}" 2>/dev/null || true
sudo launchctl load "${PLIST_DEST}"

brew services restart prometheus
brew services restart grafana

# --- Wait and verify ---
echo "==> Waiting for services to start..."
sleep 3

if curl -sf http://127.0.0.1:9256/health >/dev/null 2>&1; then
    echo "    Exporter: OK (http://127.0.0.1:9256/metrics)"
else
    echo "    Exporter: FAILED - check ${SCRIPT_DIR}/exporter.err"
fi

if curl -sf http://127.0.0.1:9090/-/healthy >/dev/null 2>&1; then
    echo "    Prometheus: OK (http://127.0.0.1:9090)"
else
    echo "    Prometheus: FAILED - check ${BREW_PREFIX}/var/log/prometheus.err.log"
fi

if curl -sf "http://127.0.0.1:${GRAFANA_PORT}/login" >/dev/null 2>&1; then
    echo "    Grafana: OK (http://127.0.0.1:${GRAFANA_PORT})"
else
    echo "    Grafana: FAILED - check ${BREW_PREFIX}/var/log/grafana-stderr.log"
fi

echo ""
echo "==> Done! Open http://localhost:${GRAFANA_PORT} (admin/admin) to view dashboards."
echo "    Edit ${SCRIPT_DIR}/config.yml to customize tracked processes."
echo "    After editing config, restart with: sudo launchctl unload ${PLIST_DEST} && sudo launchctl load ${PLIST_DEST}"
